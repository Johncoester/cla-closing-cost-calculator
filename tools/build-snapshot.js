// Builds fee-snapshot.js (embedded fallback data) from per-tab CSV exports of the
// "CLA Fee Tables (Live - Calculator)" Google Sheet.
// usage: node tools/build-snapshot.js <dir-with-TAB.csv-files>
const fs=require("fs"),dir=process.argv[2]||"/workspace/cla-data/sheet-staging";
const TABS=["CLA_Fees","Recording_Fees","Transfer_Taxes","Premium_Tiers","Premium_Rules","Endorsements","Jurisdictions"];
function parseCSV(t){const rows=[];let row=[],f="",q=false;for(let i=0;i<t.length;i++){const c=t[i];
 if(q){if(c=='"'){if(t[i+1]=='"'){f+='"';i++}else q=false}else f+=c}
 else if(c=='"')q=true;else if(c==","){row.push(f);f=""}else if(c=="\n"||c=="\r"){if(c=="\r"&&t[i+1]=="\n")i++;row.push(f);rows.push(row);row=[];f=""}else f+=c}
 if(f!==""||row.length){row.push(f);rows.push(row)}return rows.filter(r=>r.some(c=>c!==""))}
const out={};for(const t of TABS){const rows=parseCSV(fs.readFileSync(`${dir}/${t}.csv`,"utf8"));
 out[t]=rows.map((r,i)=>i===0?r:r.map(c=>c!==""&&/^-?\d+(\.\d+)?$/.test(c)?+c:c))}
fs.writeFileSync("fee-snapshot.js",`// Embedded snapshot of the CLA Fee Tables (Live - Calculator) Google Sheet, used when the live sheet
// cannot be fetched. Generated by tools/build-snapshot.js on ${new Date().toISOString().slice(0,10)}. Do not edit by hand; edit the sheet.
var CLA_FEES_SNAPSHOT=${JSON.stringify(out)};
if(typeof module!=="undefined")module.exports={CLA_FEES_SNAPSHOT};
`);console.log(Object.fromEntries(Object.entries(out).map(([k,v])=>[k,v.length-1])),fs.statSync("fee-snapshot.js").size);
