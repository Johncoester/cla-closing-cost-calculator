// Builds zip-county.js from US Census Bureau 2020 files (no API key):
//  https://www2.census.gov/geo/docs/reference/codes2020/national_county2020.txt
//  https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt
// usage: node tools/build-zip-data.js <dir-with-both-files>
const fs=require("fs"),dir=process.argv[2]||".";const ST={"24":"MD","51":"VA","11":"DC","12":"FL"};
const KEEP=new Set(["James City County","Charles City County"]);
const nm=(n)=>KEEP.has(n)?n:n.endsWith(" County")?n.slice(0,-7):/ city$/.test(n)?n.replace(/ city$/," City"):n;
const C={};for(const l of fs.readFileSync(dir+"/national_county2020.txt","utf8").split(/\r?\n/).slice(1)){const a=l.split("|");if(ST[a[1]])C[a[1]+a[2]]=[ST[a[1]],nm(a[4])]}
const Z={};for(const l of fs.readFileSync(dir+"/tab20_zcta520_county20_natl.txt","utf8").split(/\r?\n/).slice(1)){const a=l.split("|");if(!a[1]||!C[a[9]])continue;(Z[a[1]]=Z[a[1]]||[]).push([a[9],+a[16]])}
const out={};for(const z of Object.keys(Z).sort()){const tot=Z[z].reduce((s,x)=>s+x[1],0);out[z]=Z[z].sort((a,b)=>b[1]-a[1]).filter((x,i)=>i===0||x[1]/tot>=0.05).map(x=>x[0]).join(",")}
const counties=Object.fromEntries(Object.entries(C).sort((a,b)=>a[1][0].localeCompare(b[1][0])||a[1][1].localeCompare(b[1][1])));
fs.writeFileSync("zip-county.js",`// ZIP -> county lookup for MD, VA, DC, FL. Generated by tools/build-zip-data.js.
// Source: U.S. Census Bureau 2020 ZCTA-to-County Relationship File (tab20_zcta520_county20_natl.txt) and
// 2020 national county FIPS list (national_county2020.txt), downloaded ${new Date().toISOString().slice(0,10)}.
// ZCTAs approximate USPS ZIP codes. Counties listed by land-area share, largest first (others kept if >=5% of land area).
// PO-box-only / unique ZIPs have no ZCTA; the app falls back to the nearest ZCTA in the same 3-digit prefix (flagged approximate).
var CLA_COUNTIES=${JSON.stringify(counties)};
var CLA_ZIPS=${JSON.stringify(out)};
if(typeof module!=="undefined")module.exports={CLA_COUNTIES,CLA_ZIPS};
`);
const n={};for(const v of Object.values(C))n[v[0]]=(n[v[0]]||0)+1;console.log(n,Object.keys(out).length,"zips",fs.statSync("zip-county.js").size,"bytes");
